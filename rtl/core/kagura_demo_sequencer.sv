    // Sprite record generator: sprite count[8:3], byte count[2:0]; four
    // register stages (kind and sine arguments, sines, position, byte).
    function automatic signed [7:0] sine(input [7:0] i);  // one parabola per half
        reg [13:0] p;
        begin
            p=14'(i[6:0])*14'(7'd127-i[6:0]);
            sine=i[7] ? 8'sd0-$signed({1'b0,p[11:5]}) : $signed({1'b0,p[11:5]});
        end
    endfunction
    function automatic [9:0] title_tile(input [3:0] t);  // K A G U R A - 9 D E M O
        case(t)
            4'd0: title_tile=10'd48; 4'd1: title_tile=10'd49; 4'd2: title_tile=10'd50; 4'd3: title_tile=10'd51;
            4'd4: title_tile=10'd52; 4'd5: title_tile=10'd49; 4'd6: title_tile=10'd53; 4'd7: title_tile=10'd54;
            4'd8: title_tile=10'd55; 4'd9: title_tile=10'd56; 4'd10: title_tile=10'd57; default: title_tile=10'd58;
