// Hardware test stand-in for the CPU: drives the CPU-independent request
// interface after reset, like a driver would through the register window.
// 1. INC=1; palette shadow: palette p, colour i -> R=i, G=p, B=15-i
//    (colour 0 of every palette is black so tile edges stay visible).
// 2. Patterns: 16 tiles; tile t pixel (x,y) = 15 on the top row and the
//    left column (an orientation mark), else ((x+y+t) mod 15)+1.
// 3. Map 64x32: tile (col+row) mod 16, palette row mod 16, H flip on odd
//    columns of rows 8..15, V flip on odd columns of rows 16..23.
//    SPRITES=1 also initializes all OAM, with eight 16px sprites exercising
//    base-tile alignment, flips and behind; the last 56 records are disabled.
// 4. BACKDROP=0, RASTER off, DISPLAY_CTRL=display+BG, COMMIT, wait for it.
// 4b. Read back six bytes (map in both halves, pattern, palette) through
//    READ_REQUEST/READ_RESULT and flag mismatches (hardware diagnosis).
// 5. Forever: scroll X += 1 (mod 512), Y += 1 every 4 frames, COMMIT, wait
//    until COMMIT_BUSY clears (one update per frame).
// AUDIO=1 first loads triangle (ch4) and sine (ch5) waves into the wave
// shadow, enables all six voices silently and AUDIO_COMMITs, then loads the
// waves again so both banks match (every later commit swaps them). Each
// frame then advances a small song player before the scroll update: it
// writes the steps and envelope gains of all voices and AUDIO_COMMITs.
// SCENE=1 replaces the test content (steps 1..3, OAM included) with a
// vertical shooter scene, skips the read-back checks, and each update also
// rewrites the moving sprites and twinkling colours (see the scene block).
// Its enemies flap with the song rows, so it is meant for AUDIO=1.
// Accesses are spaced like a 3.375MHz CPU; a refused write is retried.
// Generated bytes come from registers up to four cycles behind count, so
// SPACING must stay at 5 or more.
module kagura_demo_sequencer #(
    parameter integer SPACING=16,
    parameter bit SPRITES=0,
    parameter bit AUDIO=0,
    parameter bit SCENE=0,
    parameter bit RASTER=0,          // write a raster scroll table before the first COMMIT (CAPS RSCROLL, LINES>=161)
    parameter [15:0] ANIM_START=0,   // SCENE: first anim value (tests start inside a wall phase)
    parameter integer LINES=240      // SCENE: logical screen height (180 for 16:9)
) (
    input wire clk, reset,
    output reg req_valid,
    input wire req_ready,
    output reg req_write,
    output reg [4:0] req_addr,
    // Kept as fabric flops: absorbed into the art BSRAM output register, the
    // slow DO would feed the register window opcode decode directly.
    (* syn_preserve=1 *) output reg [7:0] req_wdata,
    input wire rsp_valid,
    input wire [7:0] rsp_rdata,
    input wire rsp_error,
    output reg configured,           // first COMMIT done
    output reg [15:0] frames,        // animation updates committed
    output reg [31:0] map_readback,
    output reg [31:0] map_written,
    output reg map_bad, data_bad,    // read-back mismatch: map / pattern or palette
    output reg sprite_overflow       // SCENE: the last checked frame dropped sprites (SPR_OVERFLOW)
);
    localparam [4:0] STATUS=5'h00, IRQ_STATUS=5'h01, DISPLAY_CTRL=5'h03, ADDR_L=5'h04, ADDR_M=5'h05, ADDR_H=5'h06,
        VRAM_WRITE=5'h07, READ_REQUEST=5'h08, READ_RESULT=5'h09, EXT_INDEX=5'h0a, EXT_DATA=5'h0b,
        AUDIO_INDEX=5'h0c,AUDIO_DATA=5'h0d,COMMAND=5'h0e, INC_L=5'h10, INC_H=5'h11, ERROR_CODE=5'h17;
    // Program steps.
    localparam [4:0] S_INC_L=0, S_INC_H=1, S_PAL_ADDR=2, S_PAL=3, S_PAT_ADDR=4, S_PAT=5,
        S_MAP_ADDR=6, S_MAP=7, S_EXT=8, S_DISPLAY=9, S_COMMIT=10, S_WAIT=11, S_ERR_READ=12,
        S_ERR_CLEAR=13, S_SCROLL=14, S_IDLE=15, S_CHECK=16, S_OAM_ADDR=17, S_OAM=18, S_INIT=19,
        S_WAVE_ADDR=20,S_WAVE=21,S_AUDIO_CFG=22,S_AUDIO_COMMIT=23,S_AUDIO_WAIT=24,
        S_MUSIC=25,S_MUSIC_WRITE=26,S_SCENE_ADDR=27,S_SCENE_OAM=28,S_SCENE_PAL=29,
        S_OVF_READ=30,S_OVF_CLEAR=31;
    reg [4:0] step;
    // {EXT index, value}: RS_COUNT=3, RS_INDEX=0, then LINE/X_L/X_H/Y per entry.
    function automatic [15:0] rs_pair(input [4:0] j);
        case(j)
            5'd0: rs_pair={8'h0b,8'd3};
            5'd1: rs_pair={8'h0c,8'd0};
            5'd2: rs_pair={8'h0d,8'd100};
            5'd6: rs_pair={8'h0d,8'd130};
            5'd7: rs_pair={8'h0e,8'd40};
            5'd10: rs_pair={8'h0d,8'd160};
            5'd3,5'd11: rs_pair={8'h0e,8'd0};
            5'd4,5'd8,5'd12: rs_pair={8'h0f,8'd0};
            default: rs_pair={8'h10,8'd0};
        endcase
    endfunction
    reg [12:0] count;                  // byte index within a stream / sub-step
    reg [8:0] scroll_x;
    reg [7:0] scroll_y;
    reg [1:0] frame_div;

    // Initial voice setup: all six voices enabled with phase reset, STEP and
    // gains 0 (silent until the song player writes them). Pulse duty ch0 1/4,
    // ch1 1/8, ch2 1/4; wave length 256; MASTER 48.
    function automatic [15:0] audio_entry(input [6:0] n);
        reg [3:0] ch,off;
        begin
            ch=4'(n/10); off=4'(n%10);
            case(off)
                4'd3: audio_entry={ch,off,ch==1 ? 8'h20 : ch<3 ? 8'h40 : 8'h00};
                4'd6: audio_entry={ch,off,8'h03};
                4'd7: audio_entry={ch,off,ch>=4 ? 8'h08 : 8'h00};
                default: audio_entry={ch,off,8'h00};
            endcase
            if(n>=60) audio_entry=16'he030;
        end
    endfunction
    reg [15:0] audio_now;
    always @(posedge clk) audio_now<=audio_entry(count[7:1]);
    // Wave shadow bytes: ch4 (count[8]=0) triangle, ch5 a sine made of one
    // parabola per half period, h*(127-h)/32 peaking at 126.
    wire [6:0] wave_h=count[6:0];
    wire [7:0] wave_arch=8'((14'(wave_h)*14'(7'd127-wave_h))>>5);
    reg [7:0] wave_byte;
    always @(posedge clk)
        if(!count[8]) wave_byte<=count[7] ? 8'd127-{wave_h,1'b0} : {wave_h,1'b0}-8'd128;
        else wave_byte<=count[7] ? 8'd0-wave_arch : wave_arch;
    reg waves_twice;                   // second wave load (other bank) done

    // Song player: one call per frame, 128 rows of TEMPO frames (about 15s),
    // the first 64 rows without lead/echo on the first pass. A minor,
    // chords per 16-row bar Am F C G | Dm Em F G.
    // ch0 lead (vibrato after 12 frames), ch1 chord arpeggio (one tone per
    // frame), ch2 the lead three rows late, ch3 hi-hat/snare, ch4 octave
    // bass, ch5 kick (sine falling from 160Hz). Gains are software envelopes.
    // Notes are {octave, semitone}; lead codes 0 hold, 1 release.
    localparam integer TEMPO=7;
    localparam [6:0] HOLD=7'h00, REST=7'h01;
    function automatic [6:0] lead_code(input [6:0] row);
        case(row)
            7'd0: lead_code={3'd4,4'd9};   7'd3: lead_code={3'd5,4'd0};   7'd6: lead_code={3'd5,4'd4};
            7'd8: lead_code={3'd5,4'd9};   7'd12: lead_code={3'd5,4'd7};  7'd14: lead_code={3'd5,4'd4};
            7'd16: lead_code={3'd5,4'd5};  7'd20: lead_code={3'd5,4'd4};  7'd22: lead_code={3'd5,4'd0};
            7'd24: lead_code={3'd4,4'd9};  7'd28: lead_code={3'd5,4'd0};  7'd30: lead_code=REST;
            7'd32: lead_code={3'd4,4'd7};  7'd35: lead_code={3'd5,4'd0};  7'd38: lead_code={3'd5,4'd4};
            7'd40: lead_code={3'd5,4'd7};  7'd44: lead_code={3'd5,4'd9};  7'd46: lead_code={3'd5,4'd7};
            7'd48: lead_code={3'd5,4'd2};  7'd54: lead_code={3'd4,4'd11}; 7'd56: lead_code={3'd4,4'd7};
            7'd60: lead_code=REST;
            7'd64: lead_code={3'd5,4'd2};  7'd67: lead_code={3'd5,4'd5};  7'd70: lead_code={3'd5,4'd9};
            7'd74: lead_code={3'd5,4'd7};  7'd76: lead_code={3'd5,4'd5};  7'd78: lead_code={3'd5,4'd4};
            7'd80: lead_code={3'd5,4'd4};  7'd83: lead_code={3'd5,4'd7};  7'd86: lead_code={3'd5,4'd11};
            7'd90: lead_code={3'd5,4'd9};  7'd92: lead_code={3'd5,4'd7};  7'd94: lead_code={3'd5,4'd4};
            7'd96: lead_code={3'd5,4'd5};  7'd98: lead_code={3'd5,4'd9};  7'd100: lead_code={3'd6,4'd0};
            7'd104: lead_code={3'd5,4'd11};7'd106: lead_code={3'd5,4'd9}; 7'd108: lead_code={3'd5,4'd7};
            7'd110: lead_code={3'd5,4'd5}; 7'd112: lead_code={3'd5,4'd7}; 7'd116: lead_code={3'd5,4'd5};
            7'd120: lead_code={3'd5,4'd4}; 7'd122: lead_code={3'd5,4'd2}; 7'd124: lead_code={3'd4,4'd11};
            default: lead_code=HOLD;
        endcase
    endfunction
    function automatic [4:0] chord(input [2:0] bar);   // {minor, root semitone}
        case(bar)
            3'd0: chord={1'b1,4'd9}; 3'd1: chord={1'b0,4'd5}; 3'd2: chord={1'b0,4'd0}; 3'd3: chord={1'b0,4'd7};
            3'd4: chord={1'b1,4'd2}; 3'd5: chord={1'b1,4'd4}; 3'd6: chord={1'b0,4'd5}; default: chord={1'b0,4'd7};
        endcase
    endfunction
    function automatic [6:0] add_semi(input [6:0] note,input [3:0] up);
        reg [4:0] s;
        begin
            s=5'(note[3:0])+5'(up);
            add_semi=s>=12 ? {note[6:4]+3'd1,4'(s-5'd12)} : {note[6:4],s[3:0]};
        end
    endfunction
    // STEP of octave 7 (C7..B7), round(f*2^24/48000); lower octaves shift.
    function automatic [20:0] step7(input [3:0] s);
        case(s)
            4'd0: step7=21'd731558;  4'd1: step7=21'd775059;  4'd2: step7=21'd821146;
            4'd3: step7=21'd869974;  4'd4: step7=21'd921705;  4'd5: step7=21'd976513;
            4'd6: step7=21'd1034579; 4'd7: step7=21'd1096099; 4'd8: step7=21'd1161276;
            4'd9: step7=21'd1230329; 4'd10: step7=21'd1303488; default: step7=21'd1380998;
        endcase
    endfunction
    function automatic [7:0] decay(input [7:0] v,input [1:0] shift);
        reg [7:0] d;
        begin d=v>>shift; decay=v-(d==0 && v!=0 ? 8'd1 : d); end
    endfunction
    reg music_tick;                    // the program's per-frame call
    reg [2:0] tick;
    reg [6:0] row;
    reg looped;
    reg [6:0] lead_note,echo_note,bass_note,hist0,hist1,hist2;
    reg lead_gate,echo_gate,snare;
    reg [7:0] lead_level,arp_level,echo_level,noise_level,bass_level,kick_level;
    reg [15:0] kick_step;
    reg [1:0] arp_index;
    reg [4:0] vib_age;
    reg [2:0] lfo;
    wire [3:0] beat=row[3:0];
    wire [4:0] chord_now=chord(row[6:4]);
    wire [6:0] code=looped || row[6] ? lead_code(row) : HOLD;
    wire kick_hit=beat==0 || beat==8 || (row[4] && beat==10);
    wire snare_hit=beat==4 || beat==12 || (row[6:4]==3'd7 && beat>=13);
    wire [6:0] bass_root={chord_now[3:0]<5 ? 3'd3 : 3'd2,chord_now[3:0]};
    wire [6:0] bass_base=beat[3:2]==2'd3 ? add_semi(bass_root,4'd7) : bass_root;
    wire [6:0] arp_note=add_semi({3'd4,chord_now[3:0]},
        arp_index==0 ? 4'd0 : arp_index==1 ? (chord_now[4] ? 4'd3 : 4'd4) : 4'd7);
    always @(posedge clk)
        if(reset) begin
            tick<=0; row<=0; looped<=0; lead_note<=0; echo_note<=0; bass_note<=0;
            hist0<=HOLD; hist1<=HOLD; hist2<=HOLD; lead_gate<=0; echo_gate<=0; snare<=0;
            lead_level<=0; arp_level<=0; echo_level<=0; noise_level<=0; bass_level<=0; kick_level<=0;
            kick_step<=0; arp_index<=0; vib_age<=0; lfo<=0;
        end else if(music_tick) begin
            // Envelopes and sweeps; row events below override them.
            lead_level<=lead_gate ? (lead_level>8'd112 ? lead_level-8'd2 : lead_level) : decay(lead_level,2'd2);
            echo_level<=echo_gate ? (echo_level>8'd56 ? echo_level-8'd1 : echo_level) : decay(echo_level,2'd2);
            arp_level<=decay(arp_level,2'd3);
            noise_level<=decay(noise_level,snare ? 2'd2 : 2'd1);
            bass_level<=bass_level>8'd150 ? bass_level-8'd8 : bass_level;
            kick_level<=decay(kick_level,2'd2);
            if(kick_step>16'd15729) kick_step<=kick_step-(kick_step>>3);
            if(vib_age!=5'd31) vib_age<=vib_age+1'b1;
            lfo<=lfo+1'b1;
            arp_index<=arp_index==2'd2 ? 2'd0 : arp_index+1'b1;
            tick<=tick==3'(TEMPO-1) ? 3'd0 : tick+1'b1;
            if(tick==3'(TEMPO-1)) begin row<=row+1'b1; if(row==7'd127) looped<=1; end
            if(tick==0) begin
                if(code>REST) begin lead_note<=code; lead_gate<=1; lead_level<=8'd160; vib_age<=0; end
                else if(code==REST) lead_gate<=0;
                hist0<=code; hist1<=hist0; hist2<=hist1;
                if(hist2>REST) begin echo_note<=hist2; echo_gate<=1; echo_level<=8'd80; end
                else if(hist2==REST) echo_gate<=0;
                arp_level<=8'd72;
                if(kick_hit) begin kick_level<=8'd255; kick_step<=16'd55924; end
                if(snare_hit) begin snare<=1; noise_level<=8'd200; end
                else if(!beat[0]) begin snare<=0; noise_level<=beat[1] ? 8'd80 : 8'd40; end
                if(!beat[0]) begin
                    bass_note<={bass_base[6:4]+{2'd0,beat[1]},bass_base[3:0]};
                    bass_level<=8'd230;
                end
            end
        end
    // Per-frame register list, entry count[5:1] (index, then data): STEP
    // bytes and L/R gains of each voice, the noise period. ch1 sits left,
    // ch2 right, ch3 slightly right. Bytes pass four register stages.
    function automatic [7:0] entry_index(input [4:0] e);
        case(e)
            5'd0: entry_index=8'h00;  5'd1: entry_index=8'h01;  5'd2: entry_index=8'h02;
            5'd3: entry_index=8'h04;  5'd4: entry_index=8'h05;  5'd5: entry_index=8'h10;
            5'd6: entry_index=8'h11;  5'd7: entry_index=8'h12;  5'd8: entry_index=8'h14;
            5'd9: entry_index=8'h15;  5'd10: entry_index=8'h20; 5'd11: entry_index=8'h21;
            5'd12: entry_index=8'h22; 5'd13: entry_index=8'h24; 5'd14: entry_index=8'h25;
            5'd15: entry_index=8'h38; 5'd16: entry_index=8'h34; 5'd17: entry_index=8'h35;
            5'd18: entry_index=8'h40; 5'd19: entry_index=8'h41; 5'd20: entry_index=8'h42;
            5'd21: entry_index=8'h44; 5'd22: entry_index=8'h45; 5'd23: entry_index=8'h50;
            5'd24: entry_index=8'h51; 5'd25: entry_index=8'h52; 5'd26: entry_index=8'h54;
            default: entry_index=8'h55;
        endcase
    endfunction
    reg [4:0] entry_a,entry_b,entry_c;
    reg [6:0] note_a;
    reg [20:0] step_b;
    reg [23:0] step_c;
    reg [15:0] music_now;
    always @(posedge clk) begin
        entry_a<=count[5:1];
        case(count[5:1])
            5'd0,5'd1,5'd2: note_a<=lead_note;
            5'd5,5'd6,5'd7: note_a<=arp_note;
            5'd10,5'd11,5'd12: note_a<=echo_note;
            default: note_a<=bass_note;
        endcase
        entry_b<=entry_a;
        step_b<=step7(note_a[3:0])>>(3'd7-note_a[6:4]);
        entry_c<=entry_b;
        if(entry_b>=5'd23) step_c<={8'd0,kick_step};
        else if(entry_b<5'd3 && vib_age>=5'd12) case(lfo)
            3'd1,3'd3: step_c<=24'(step_b)+24'(step_b>>8);
            3'd2: step_c<=24'(step_b)+24'(step_b>>7);
            3'd5,3'd7: step_c<=24'(step_b)-24'(step_b>>8);
            3'd6: step_c<=24'(step_b)-24'(step_b>>7);
            default: step_c<=24'(step_b);
        endcase
        else step_c<=24'(step_b);
        music_now[15:8]<=entry_index(entry_c);
        case(entry_c)
            5'd0,5'd5,5'd10,5'd18,5'd23: music_now[7:0]<=step_c[7:0];
            5'd1,5'd6,5'd11,5'd19,5'd24: music_now[7:0]<=step_c[15:8];
            5'd2,5'd7,5'd12,5'd20,5'd25: music_now[7:0]<=step_c[23:16];
            5'd3,5'd4: music_now[7:0]<=lead_level;
            5'd8: music_now[7:0]<=arp_level;
            5'd9: music_now[7:0]<=arp_level>>1;
            5'd13: music_now[7:0]<=echo_level>>1;
            5'd14: music_now[7:0]<=echo_level;
            5'd15: music_now[7:0]<=snare ? 8'd2 : 8'd0;
            5'd16: music_now[7:0]<=noise_level-(noise_level>>2);
            5'd17: music_now[7:0]<=noise_level;
            5'd21,5'd22: music_now[7:0]<=bass_level;
            default: music_now[7:0]<=kick_level;
        endcase
    end

    // Read-back checks: {address, expected}; entries 0..3 are map bytes.
    function automatic [23:0] check_entry(input [2:0] n);
        case(n)
            3'd0: check_entry={16'h8082,8'h02};  // map word 65: tile 2, palette 1
            3'd1: check_entry={16'h8083,8'h04};
            3'd2: check_entry={16'h880a,8'h05};  // map word 1029 (second RAM): V flip, tile 5
            3'd3: check_entry={16'h880b,8'h80};
            3'd4: check_entry={16'h0024,8'hf4};  // tile 1 row 1 byte 0
            default: check_entry={16'h943e,8'h10}; // palette 1 colour 15 = 0xF10, low byte
        endcase
    endfunction
    wire [23:0] check_now=check_entry(count[5:3]);
    // Generated data for the current stream byte.
    wire [7:0] pal_word=count[8:1];    // palette p=word[7:4], colour i=word[3:0]
    wire [3:0] pal_p=pal_word[7:4], pal_i=pal_word[3:0];
    wire [11:0] pal_rgb=pal_i==0 ? 12'h000 : {pal_i,pal_p,4'd15-pal_i};
    wire [7:0] pal_byte=count[0] ? {4'h0,pal_rgb[11:8]} : pal_rgb[7:0];
    function automatic [3:0] tile_pixel(input [3:0] t,input [2:0] x,input [2:0] y);
        integer v;
        begin
            if(x==0 || y==0) tile_pixel=4'd15;
            else begin v=(x+y+t)%15; tile_pixel=4'(v+1); end
        end
    endfunction
    wire [3:0] pat_t=count[8:5];
    wire [2:0] pat_y=count[4:2];
    wire [2:0] pat_x=3'({count[1:0],1'b0});
    wire [7:0] pat_byte={tile_pixel(pat_t,pat_x,pat_y),tile_pixel(pat_t,pat_x+3'd1,pat_y)};
    wire [10:0] map_word=count[11:1];  // row=word[10:6], col=word[5:0]
    wire [4:0] map_row=map_word[10:6];
    wire [5:0] map_col=map_word[5:0];
    wire map_h=map_col[0] && map_row[4:3]==2'd1;
    wire map_v=map_col[0] && map_row[4:3]==2'd2;
    wire [15:0] map_entry={map_v,map_h,map_row[3:0],6'd0,4'(map_col+map_row)};
    wire [7:0] map_byte=count[0] ? map_entry[15:8] : map_entry[7:0];
    wire [5:0] oam_n=count[8:3];
    reg [7:0] oam_byte;
    always @* begin
        oam_byte=0;
        if(oam_n<8) case(count[2:0])
            3'd0: oam_byte=8'd32+8'(oam_n*24);
            3'd2: oam_byte=8'd40+{oam_n[1:0],5'b0};
            3'd4: oam_byte={4'b0,oam_n[1:0],2'b11};
            3'd5: oam_byte={2'b0,4'(15-oam_n),2'b0};
            3'd6: oam_byte={3'b0,oam_n[2:0],2'b11};
            default: ;
        endcase
    end

    // SCENE=1 content: a vertical shooter. Tiles come from kagura_demo_art
    // (tools/gen-demo-art.py). The map is a hashed starfield (tiles 1..5,
    // random flips) with a 4x4-tile planet at rows 6..9, columns 26..29;
    // scroll Y = -anim moves it down one pixel per update. Sprites, as
    // functions of anim (updates committed) and the song row:
    //   0 ship (y=LINES-44: 196, or 136 on the 180-line screen), 1 engine
    //   flame, 2..5 shots (one launched every 8 updates, hidden after 24
    //   updates, 120 lines above the ship), 6..9 enemy shots from the lower enemy row,
    //   10..25 enemy formation 2x8 (flaps every two song rows),
    //   26..29 fast streak stars, 30..41 title "KAGURA-9 DEMO" at y=12,
    //   42..63 a 22-wide enemy wall that crosses the 16 sprites/line limit.
    // anim[9:8] selects the wall phase (256 updates each): 0 and 3 hidden,
    // 1 descending in fixed OAM order (the highest slots drop out on its
    // lines), 2 the same with the members rotated by 8 slots per update
    // (software flicker: every member is dropped one update in three).
    // Each update rewrites all OAM, palette 0 colours 6/7 (twinkle) and
    // palette 6 colour 1 (rainbow title) before COMMIT.
    reg [15:0] anim;
    reg [4:0] rotate;                  // 8*anim mod 22
    wire [31:0] art_word;
    generate if(SCENE) begin: scene_art
