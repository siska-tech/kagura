    endfunction
    localparam [3:0] K_OFF=0, K_SHIP=1, K_FLAME=2, K_SHOT=3, K_ESHOT=4, K_ENEMY=5, K_STAR=6,
        K_TITLE=7, K_WALL=8;
    wire [5:0] sprite_n=count[8:3];
    wire [1:0] shot_slot=2'(sprite_n-6'd2);
    wire [1:0] eshot_slot=2'(sprite_n-6'd6);
    wire [3:0] enemy_slot=4'(sprite_n-6'd10);
    wire [4:0] wall_slot=5'(sprite_n-6'd42);
    wire [5:0] wall_turned={1'b0,wall_slot}+{1'b0,rotate};
    wire wall_flicker=anim[9:8]==2'd2;
    wire wall_on=anim[9:8]==2'd1 || wall_flicker;
    wire [4:0] shot_age=5'(anim)+{shot_slot,3'd0};
    wire [15:0] eshot_time=anim+{9'd0,eshot_slot,5'd0};  // age bits 6:0, cycle bits 15:7
    wire [2:0] eshot_col=3'(eshot_time[9:7]*3)+{eshot_slot,1'b0};
    wire [15:0] shot_launch=anim-{11'd0,shot_age};
    wire [15:0] eshot_launch=anim-{9'd0,eshot_time[6:0]};
    reg [3:0] kind_a,kind_b;
    reg [2:0] byte_a,byte_b,byte_c,col_a,col_b;
    reg [4:0] slot_a,slot_b;          // star, title letter or wall member
    reg [6:0] age_a,age_b;
    reg row_a,row_b;
    reg [7:0] arg1_a,arg2_a;
    reg signed [7:0] sine1_b,sine2_b;
    reg [9:0] x_c,y_c,tile_c;
    reg [3:0] pal_c;
    reg big_c,enable_c;
    reg [7:0] scene_oam_byte;
    wire signed [10:0] sine1=sine1_b, sine2=sine2_b;
    wire signed [10:0] ship_dx=((sine1<<<2)+sine1)>>>3;   // +-78
    wire signed [10:0] enemy_dx=((sine1<<<1)+sine1)>>>3;  // +-47
    wire signed [10:0] bob=sine2>>>5, ripple=sine2>>>4;
    // The ship sits 44 lines above the bottom so it stays on a 180-line screen.
    localparam signed [10:0] SHIP_Y=11'(LINES-44);
    always @(posedge clk) begin
        byte_a<=count[2:0];
        kind_a<=K_OFF; slot_a<=0; age_a<=0; col_a<=0; row_a<=0; arg1_a<=0; arg2_a<=0;
        if(sprite_n<2) begin
            kind_a<=sprite_n==0 ? K_SHIP : K_FLAME; arg1_a<=8'(anim*3); arg2_a<={anim[4:0],3'd0};
        end else if(sprite_n<6) begin
            kind_a<=K_SHOT; age_a<={2'd0,shot_age}; arg1_a<=8'(shot_launch*3);
        end else if(sprite_n<10) begin
            kind_a<=K_ESHOT; age_a<=eshot_time[6:0]; col_a<=eshot_col;
            arg1_a<=eshot_launch[7:0]; arg2_a<={eshot_launch[5:0],2'd0}+{eshot_col,5'd0};
        end else if(sprite_n<26) begin
            kind_a<=K_ENEMY; col_a<=enemy_slot[2:0]; row_a<=enemy_slot[3];
            arg1_a<=anim[7:0]; arg2_a<={anim[5:0],2'd0}+{enemy_slot[2:0],5'd0};
        end else if(sprite_n<30) begin kind_a<=K_STAR; slot_a<=5'(sprite_n-6'd26); end
        else if(sprite_n<42) begin kind_a<=K_TITLE; slot_a<=5'(sprite_n-6'd30); end
        else begin
            kind_a<=K_WALL;
            slot_a<=!wall_flicker ? wall_slot : wall_turned>=22 ? 5'(wall_turned-6'd22) : wall_turned[4:0];
        end

        kind_b<=kind_a; byte_b<=byte_a; slot_b<=slot_a; age_b<=age_a; col_b<=col_a; row_b<=row_a;
        sine1_b<=sine(arg1_a); sine2_b<=sine(arg2_a);

        byte_c<=byte_b; x_c<=0; y_c<=0; tile_c<=0; pal_c<=0; big_c<=0; enable_c<=0;
        case(kind_b)
            K_SHIP: begin x_c<=10'(11'sd152+ship_dx); y_c<=10'(SHIP_Y+bob); tile_c<=10'd12; pal_c<=4'd1; big_c<=1; enable_c<=1; end
            K_FLAME: begin x_c<=10'(11'sd156+ship_dx); y_c<=10'(SHIP_Y+11'sd15+bob); tile_c<=10'd9+{9'd0,anim[1]}; pal_c<=4'd1; enable_c<=1; end
            K_SHOT: begin
                x_c<=10'(11'sd156+ship_dx); y_c<=10'(SHIP_Y-11'sd4-11'(age_b)*11'd5); tile_c<=10'd7; pal_c<=4'd4;
                enable_c<=age_b<=7'd24;
            end
            K_ESHOT: begin
                x_c<=10'(11'sd72+11'(col_b)*11'sd24+enemy_dx); y_c<=10'(11'sd74+ripple+11'(age_b)*11'sd2);
                tile_c<=10'd8; pal_c<=4'd4; enable_c<=1;
            end
            K_ENEMY: begin
                x_c<=10'(11'sd68+11'(col_b)*11'sd24+enemy_dx); y_c<=10'(11'sd36+(row_b ? 11'sd24 : 11'sd0)+ripple);
                tile_c<=(row_b ? 10'd16 : 10'd24)+{7'd0,row[1]^col_b[0],2'd0}; pal_c<=row_b ? 4'd2 : 4'd3;
                big_c<=1; enable_c<=1;
            end
            K_STAR: begin
                x_c<=10'(11'(slot_b)*11'd80+11'd37);
                y_c<={2'd0,8'(8'(slot_b)*8'd67+8'(anim*3))}-10'd8; tile_c<=10'd6; enable_c<=1;
            end
            K_TITLE: begin
                x_c<=10'd108+{2'd0,slot_b<8 ? 5'(slot_b) : 5'(slot_b+5'd1),3'd0}; y_c<=10'd12;
                tile_c<=title_tile(slot_b[3:0]); pal_c<=4'd6; enable_c<=1;
            end
            K_WALL: begin
                x_c<=10'(11'(slot_b)*11'd14+11'd5); y_c<={2'd0,anim[7:0]}-10'd16;
                tile_c<=10'd16+{7'd0,row[1]^slot_b[0],2'd0}; pal_c<=4'd5; big_c<=1; enable_c<=wall_on;
            end
            default: ;
        endcase

        case(byte_c)
            3'd0: scene_oam_byte<=x_c[7:0];
            3'd1: scene_oam_byte<={6'd0,x_c[9:8]};
            3'd2: scene_oam_byte<=y_c[7:0];
            3'd3: scene_oam_byte<={6'd0,y_c[9:8]};
            3'd4: scene_oam_byte<=tile_c[7:0];
            3'd5: scene_oam_byte<={2'd0,pal_c,tile_c[9:8]};
            3'd6: scene_oam_byte<={6'd0,big_c,enable_c};
            default: scene_oam_byte<=0;
        endcase
    end
    wire [7:0] pal_out=SCENE ? scene_pal_byte : pal_byte;
    wire [7:0] pat_out=SCENE ? scene_pat_byte : pat_byte;
    wire [7:0] oam_out=SCENE ? scene_oam_byte : oam_byte;
    wire [7:0] map_out=SCENE ? scene_map_byte : map_byte;

    // One register access at a time, then SPACING idle cycles.
    reg busy, waiting, poll_read;
    reg [7:0] gap;
    reg [7:0] read_value;
    reg last_error;
    task automatic issue(input reg w,input reg [4:0] a,input reg [7:0] d);
        begin req_valid<=1; req_write<=w; req_addr<=a; req_wdata<=d; busy<=1; end
    endtask
    always @(posedge clk)
        music_tick<=!reset && !busy && gap==0 && step==S_MUSIC && !(last_error && req_write && req_addr==VRAM_WRITE);
    always @(posedge clk)
        if(reset) begin
            step<=S_INIT; count<=0; scroll_x<=0; scroll_y<=0; frame_div<=0; anim<=ANIM_START; rotate<=5'(8*ANIM_START%22); sprite_overflow<=0;
            req_valid<=0; req_write<=0; req_addr<=0; req_wdata<=0;
            busy<=0; waiting<=0; gap<=0; read_value<=0; last_error<=0; waves_twice<=0;
            configured<=0; frames<=0; map_bad<=0; data_bad<=0; map_readback<=0; map_written<=0;
        end else if(busy) begin
            if(req_valid && req_ready) begin req_valid<=0; waiting<=1; end
            if(waiting && rsp_valid) begin
                waiting<=0; busy<=0; gap<=8'(SPACING); read_value<=rsp_rdata; last_error<=rsp_error;
            end
        end else if(gap!=0) gap<=gap-1'b1;
        else begin
            // A refused VRAM write is repeated; the address did not advance.
            if(last_error && req_write && req_addr==VRAM_WRITE) issue(1,VRAM_WRITE,req_wdata);
            else case(step)
                S_INIT: if(req_addr==STATUS && !req_write && read_value[0]) step<=S_INC_L;
                    else issue(0,STATUS,8'h00);
                S_INC_L: begin issue(1,INC_L,8'd1); step<=S_INC_H; end
                S_INC_H: begin issue(1,INC_H,8'd0); step<=AUDIO ? S_WAVE_ADDR : S_PAL_ADDR; count<=0; end
                S_WAVE_ADDR: begin
                    case(count[1:0])
                        0: issue(1,ADDR_L,0);
                        1: issue(1,ADDR_M,8'h98);
                        default: issue(1,ADDR_H,0);
                    endcase
                    if(count==2) begin step<=S_WAVE; count<=0; end else count<=count+1'b1;
                end
                S_WAVE: begin
                    issue(1,VRAM_WRITE,wave_byte);
                    if(count==511) begin step<=waves_twice ? S_AUDIO_COMMIT : S_AUDIO_CFG; count<=0; end
                    else count<=count+1'b1;
                end
                S_AUDIO_CFG: begin
                    if(!count[0]) issue(1,AUDIO_INDEX,audio_now[15:8]);
                    else issue(1,AUDIO_DATA,audio_now[7:0]);
                    if(count==121) begin step<=S_AUDIO_COMMIT; count<=0; end else count<=count+1'b1;
                end
                S_AUDIO_COMMIT: begin issue(1,COMMAND,8'h04); step<=S_AUDIO_WAIT; end
                // music_tick fires now; the gap lets the list bytes settle.
                S_MUSIC: begin gap<=8'(SPACING); step<=S_MUSIC_WRITE; count<=0; end
                S_MUSIC_WRITE: begin
                    if(!count[0]) issue(1,AUDIO_INDEX,music_now[15:8]);
                    else issue(1,AUDIO_DATA,music_now[7:0]);
                    if(count==55) begin step<=S_AUDIO_COMMIT; count<=0; end else count<=count+1'b1;
                end
                S_AUDIO_WAIT: begin
                    // APPLY_BUSY clear: next frame step, the second wave
                    // load, or the video setup.
                    if(req_addr==AUDIO_DATA && !req_write && !read_value[0]) begin
                        count<=0;
                        if(configured) step<=S_SCROLL;
                        else if(waves_twice) step<=S_PAL_ADDR;
                        else begin waves_twice<=1; step<=S_WAVE_ADDR; end
                    end else if(req_addr!=AUDIO_INDEX && req_addr!=AUDIO_DATA) issue(1,AUDIO_INDEX,8'he1);
                    else issue(0,AUDIO_DATA,0);
                end
                S_PAL_ADDR: begin
                    case(count[1:0])
                        2'd0: issue(1,ADDR_L,8'h00);
                        2'd1: issue(1,ADDR_M,8'h94);
                        default: issue(1,ADDR_H,8'h00);
                    endcase
                    if(count[1:0]==2'd2) begin step<=S_PAL; count<=0; end else count<=count+1'b1;
                end
                S_PAL: begin
                    issue(1,VRAM_WRITE,pal_out);
                    if(count==13'd511) begin step<=S_PAT_ADDR; count<=0; end else count<=count+1'b1;
                end
                S_PAT_ADDR: begin
                    case(count[1:0])
                        2'd0: issue(1,ADDR_L,8'h00);
                        2'd1: issue(1,ADDR_M,8'h00);
                        default: issue(1,ADDR_H,8'h00);
                    endcase
                    if(count[1:0]==2'd2) begin step<=S_PAT; count<=0; end else count<=count+1'b1;
                end
                S_PAT: begin
                    issue(1,VRAM_WRITE,pat_out);
                    if(count==(SCENE ? 13'd2047 : 13'd511)) begin
                        step<=SPRITES || SCENE ? S_OAM_ADDR : S_MAP_ADDR; count<=0;
                    end else count<=count+1'b1;
                end
                S_OAM_ADDR: begin
                    case(count[1:0])
                        2'd0: issue(1,ADDR_L,8'h00);
                        2'd1: issue(1,ADDR_M,8'h90);
                        default: issue(1,ADDR_H,8'h00);
                    endcase
                    if(count[1:0]==2'd2) begin step<=S_OAM; count<=0; end else count<=count+1'b1;
                end
                S_OAM: begin
                    issue(1,VRAM_WRITE,oam_out);
                    if(count==13'd511) begin step<=S_MAP_ADDR; count<=0; end else count<=count+1'b1;
                end
                S_MAP_ADDR: begin
                    case(count[1:0])
                        2'd0: issue(1,ADDR_L,8'h00);
                        2'd1: issue(1,ADDR_M,8'h80);
                        default: issue(1,ADDR_H,8'h00);
                    endcase
                    if(count[1:0]==2'd2) begin step<=S_MAP; count<=0; end else count<=count+1'b1;
                end
                S_MAP: begin
                    issue(1,VRAM_WRITE,map_out);
                    // Capture the source bytes matching the read-back probes.
                    case(count)
                        13'd130: map_written[31:24]<=map_byte;
                        13'd131: map_written[23:16]<=map_byte;
                        13'd2058: map_written[15:8]<=map_byte;
                        13'd2059: map_written[7:0]<=map_byte;
                        default: ;
                    endcase
                    if(count==13'd4095) begin step<=S_EXT; count<=0; end else count<=count+1'b1;
                end
                S_EXT: begin
                    // EXT 03 BACKDROP=0, 04 RASTER=255 (off); the scene also
                    // sets 02 scroll Y=-anim for its first frame. RASTER then
                    // writes a 3-entry table: lines 100..129 fixed, 130..159
                    // shifted by 40 pixels, 160.. fixed.
                    case(count)
                        13'd0: issue(1,EXT_INDEX,8'h03);
                        13'd1: issue(1,EXT_DATA,8'h00);
                        13'd2: issue(1,EXT_INDEX,8'h04);
                        13'd3: issue(1,EXT_DATA,8'hff);
                        13'd4: issue(1,EXT_INDEX,8'h02);
                        13'd5: issue(1,EXT_DATA,8'(16'd0-anim));
                        default: issue(1,count[0] ? EXT_DATA : EXT_INDEX,
                            count[0] ? rs_pair(5'((count-13'd6)>>1))[7:0] : rs_pair(5'((count-13'd6)>>1))[15:8]);
                    endcase
                    if(count==(RASTER ? 13'd33 : SCENE ? 13'd5 : 13'd3)) begin step<=S_DISPLAY; count<=0; end else count<=count+1'b1;
                end
                S_DISPLAY: begin issue(1,DISPLAY_CTRL,SPRITES || SCENE ? 8'h07 : 8'h03); step<=S_COMMIT; end
                S_COMMIT: begin issue(1,COMMAND,8'h03); step<=S_WAIT; end
                S_WAIT: begin
                    // Poll STATUS until COMMIT_BUSY (b4) clears.
                    if(req_addr==STATUS && !req_write && !read_value[4]) begin
                        if(!configured) begin configured<=1; step<=SCENE ? S_ERR_READ : S_CHECK; count<=0; end
                        else begin frames<=frames+1'b1; step<=SCENE ? S_OVF_READ : AUDIO ? S_MUSIC : S_SCROLL; count<=0; end
                    end else issue(0,STATUS,8'h00);
                end
                S_CHECK: case(count[2:0])
                    // Entry count[5:3]: set the address, READ_REQUEST, poll STATUS
                    // until READ_READY (b2), read READ_RESULT, compare.
                    3'd0: begin issue(1,ADDR_L,check_now[15:8]); count<=count+1'b1; end
                    3'd1: begin issue(1,ADDR_M,check_now[23:16]); count<=count+1'b1; end
                    3'd2: begin issue(1,ADDR_H,8'h00); count<=count+1'b1; end
                    3'd3: begin issue(1,READ_REQUEST,8'h00); count<=count+1'b1; end
                    3'd4: begin issue(0,STATUS,8'h00); count<=count+1'b1; end
                    3'd5: if(read_value[2]) begin issue(0,READ_RESULT,8'h00); count<=count+1'b1; end
                        else issue(0,STATUS,8'h00);
                    default: begin
                        if(count[5:3]<3'd4) map_readback[31-8*count[4:3] -: 8]<=read_value;
                        if(read_value!=check_now[7:0]) begin
                            if(count[5:3]<3'd4) map_bad<=1; else data_bad<=1;
                        end
                        if(count[5:3]==3'd5) step<=S_ERR_READ;
                        else count<={count[12:6],count[5:3]+3'd1,3'd0};
                    end
                endcase
                S_ERR_READ: begin issue(0,ERROR_CODE,8'h00); step<=S_ERR_CLEAR; end
                S_ERR_CLEAR: begin issue(1,ERROR_CODE,read_value); step<=S_SCROLL; count<=0; end
                S_SCROLL: begin
                    // EXT 00 X low, 01 X bit 8, 02 Y; then (scene sprites,) COMMIT.
                    // The scene keeps X=0 and moves Y=-anim.
                    case(count[2:0])
                        3'd0: begin
                            scroll_x<=scroll_x+1'b1; frame_div<=frame_div+1'b1; anim<=anim+1'b1;
                            rotate<=rotate>=5'd14 ? rotate-5'd14 : rotate+5'd8;
                            if(frame_div==2'd3) scroll_y<=scroll_y+1'b1;
                            issue(1,EXT_INDEX,8'h00);
                        end
                        3'd1: issue(1,EXT_DATA,SCENE ? 8'd0 : scroll_x[7:0]);
                        3'd2: issue(1,EXT_INDEX,8'h01);
                        3'd3: issue(1,EXT_DATA,SCENE ? 8'd0 : {7'b0,scroll_x[8]});
                        3'd4: issue(1,EXT_INDEX,8'h02);
                        default: issue(1,EXT_DATA,SCENE ? 8'(16'd0-anim) : scroll_y);
                    endcase
                    if(count[2:0]==3'd5) begin step<=SCENE ? S_SCENE_ADDR : S_COMMIT; count<=0; end
                    else count<=count+1'b1;
                end
                S_SCENE_ADDR: begin
                    case(count[1:0])
                        2'd0: issue(1,ADDR_L,8'h00);
                        2'd1: issue(1,ADDR_M,8'h90);
                        default: issue(1,ADDR_H,8'h00);
                    endcase
                    if(count[1:0]==2'd2) begin step<=S_SCENE_OAM; count<=0; end else count<=count+1'b1;
                end
                S_SCENE_OAM: begin
                    issue(1,VRAM_WRITE,scene_oam_byte);
                    if(count==13'd511) begin step<=S_SCENE_PAL; count<=0; end else count<=count+1'b1;
                end
                S_SCENE_PAL: begin
                    // count 0..2 address of word 06, 4..7 words 06/07;
                    // 8..10 address of word 61, 12..13 word 61.
                    case(count[2:0])
                        3'd0: issue(1,ADDR_L,count[3] ? 8'hc2 : 8'h0c);
                        3'd1: issue(1,ADDR_M,8'h94);
                        3'd2: issue(1,ADDR_H,8'h00);
                        default: issue(1,VRAM_WRITE,scene_pal_byte);
                    endcase
                    if(count==13'd2 || count==13'd10) count<=count+13'd2;
                    else if(count==13'd13) begin step<=S_COMMIT; count<=0; end
                    else count<=count+1'b1;
                end
                // Sample and clear SPR_OVERFLOW once per update.
                S_OVF_READ: begin issue(0,IRQ_STATUS,8'h00); step<=S_OVF_CLEAR; end
                S_OVF_CLEAR: begin
                    sprite_overflow<=read_value[5]; issue(1,IRQ_STATUS,read_value&8'h20);
                    step<=AUDIO ? S_MUSIC : S_SCROLL; count<=0;
                end
                default: ;
            endcase
        end
endmodule
