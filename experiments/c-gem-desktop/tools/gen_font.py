"""Generate software/desktop/core/kd_font_data.c from the repository's Misaki KJ8F font.

Two printable-ASCII fonts (0x20..0x7E) are extracted, glyphs unchanged:
  system: 8x8 cells from the full-width forms (U+FF01..U+FF5E, space U+3000)
  small:  4x8 cells from the half-width forms (columns 2..5 of the 8x8 cell)

Usage: python3 -I gen_font.py [--check]
--check fails if the committed file differs from what would be generated.
"""
import hashlib
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCE = ROOT / 'software/micropython/fonts/misaki8.kfnt'
OUTPUT = HERE.parents[2] / 'software/desktop/core/kd_font_data.c'
SOURCE_SHA256 = 'cbfb1071801f7ed3b6637bb6763219e59d86c13bd149169bbbab5bca753d9238'


def load():
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit('unexpected %s sha256 %s' % (SOURCE, digest))
    if data[:4] != b'KJ8F' or struct.unpack_from('<H', data, 4)[0] != 1:
        raise SystemExit('not a KJ8F v1 file')
    count = struct.unpack_from('<H', data, 6)[0]
    glyphs = {}
    for i in range(count):
        code, = struct.unpack_from('<H', data, 8 + 10 * i)
        glyphs[code] = data[10 + 10 * i:18 + 10 * i]
    return glyphs


def table(name, rows):
    lines = ['static const uint8_t %s[95 * 8] = {' % name]
    for i in range(95):
        lines.append('    ' + ', '.join('0x%02x' % b for b in rows[i]) +
                     ',  // %r' % chr(0x20 + i))
    lines.append('};')
    return lines


def generate():
    glyphs = load()
    system, small = [], []
    for c in range(0x20, 0x7f):
        system.append(glyphs[0x3000 if c == 0x20 else 0xFF00 + c - 0x20])
        small.append(bytes((r << 2) & 0xF0 for r in glyphs[c]))
    out = [
        '// SPDX-License-Identifier: LicenseRef-Misaki',
        '// Generated by tools/gen_font.py from software/micropython/fonts/misaki8.kfnt',
        '// (sha256 %s). Do not edit.' % SOURCE_SHA256,
        '// Misaki Gothic, Copyright (C) 2002-2021 Num Kadoma. Free software: unlimited',
        '// permission to use, copy and distribute, with or without modification',
        '// (see software/micropython/fonts/README.md). Glyph shapes are unchanged.',
        '#include "kd_font.h"',
        '',
    ]
    out += table('system_rows', system) + ['']
    out += table('small_rows', small) + ['']
    out += ['const kd_font kd_font_system = {8, 8, system_rows};',
            'const kd_font kd_font_small = {4, 8, small_rows};', '']
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        if OUTPUT.read_text() != text:
            raise SystemExit('%s is stale; run tools/gen_font.py' % OUTPUT)
        print('font data up to date')
        return
    OUTPUT.write_text(text)
    print('wrote', OUTPUT)


if __name__ == '__main__':
    main()
