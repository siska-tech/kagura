#!/usr/bin/env python3
import json
from pathlib import Path
r = Path(__file__).resolve().parents[1]
expected = dict(hello=9, arithmetic=49995000, strings=384, collections=4032,
               objects=32640, fibers=480, foreign=1000, sprite16=1920, events=2592, repeat_gc=4950)
lines = ['/* Generated by tools/gen_workloads.py; committed for cross builds. */',
         'typedef struct { const char *name, *source; double expected; } Workload;',
         'static const Workload workloads[] = {']
for name, value in expected.items():
    source = (r / 'workloads' / (name + '.wren')).read_text(encoding='utf-8')
    lines.append('{'+json.dumps(name)+','+json.dumps(source, ensure_ascii=False)+','+str(value)+'},')
lines.append('};')
(r / 'src/workloads.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
