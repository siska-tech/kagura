# Writes the generated test songs (MicroPython unix port with kagura_audio):
#   MICROPYPATH=software/micropython micropython software/audio/tools/make_fixtures.py software/audio/songs
# click.ksn: a timing probe. One pulse voice, a C-6 click on every row cut
# after one tick (C01) and five ticks of silence, 150 BPM speed 6: a row is
# exactly 100 ms and every click starts from silence, so the onsets in an
# HDMI recording show the player's timing (tools/kagura-audio-timing.py).
import sys

from kagura.music import Song, Pattern, instrument, KIND_PULSE

folder = sys.argv[1]


def click_song():
    s = Song(voices=(0,), rows=64)
    s.title, s.author = 'CLICK', 'KAGURA TEST'
    s.tempo, s.speed = 150, 6
    s.instruments = [instrument(KIND_PULSE, 128, 15, 128, 0, 0, 15, 0)]
    p = s.patterns[0]
    for r in range(64):
        o = p.offset(r, 0)
        p.cells[o], p.cells[o + 1] = 73, 0        # C-6, instrument 00
        p.cells[o + 3], p.cells[o + 4] = 0xC, 1   # cut after one tick
    return s


def c_header(name, data):
    lines = ['// %s: generated by software/audio/tools/make_fixtures.py' % name, '#include <stdint.h>',
             'static const uint8_t ksng_%s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('    ' + ''.join('0x%02x,' % b for b in data[i:i + 16]))
    lines.append('};\n')
    return '\n'.join(lines)


data = click_song().to_bytes()
with open(folder + '/click.ksn', 'wb') as f:
    f.write(data)
with open(folder + '/click.h', 'w') as f:
    f.write(c_header('click', data))
print('click.ksn', len(data))
